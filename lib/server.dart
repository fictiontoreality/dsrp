class Challenge {
  final List<int> ephemeralServerPublicKey;
  final List<int> salt;

  Challenge({required this.ephemeralServerPublicKey, required this.salt});
}

class Server {
  /// User identifier.
  final String userId;
  /// Salt provided by user during registration.
  final List<int> salt;
  /// Verifier key provided by user during registration.
  final BigInt verifierKey;
  /// Ephemeral public user key generated by user to initiate a session.
  final List<int> ephemeralUserPublicKey;
  /// A generator modulo N.
  /// Typically denoted 'g'.
  final BigInt generator;
  /// Hash algorithm used during SRP key and verifier calculations (e.g., SHA256).
  final HashAlgorithm hashAlgorithm;
  /// A large, safe prime.
  /// Typically denoted 'N'.
  /// By definition a safe prime N = 2q + 1, where q is a Sophie Germain prime.
  /// All arithmetic is performed in the field of integers modulo N.
  final BigInt safePrime;

  BigInt? serverPrivateKey;
  BigInt? serverPublicKey;

  Server({
      required this.userId,
      required this.salt,
      required List<int> verifierKey,
      required this.ephemeralUserPublicKey,
      BigInt? generator,
      BigInt? safePrime,
      HashAlgorithm? hashAlgorithm,
  }) : verifierKey = verifierKey.toBigInt(),
       generator = generator ?? BigInt.from(2),
       safePrime = safePrime ?? defaultSafePrime,
       hashAlgorithm = hashAlgorithm ?? defaultHashAlgorithm;

  Future<Challenge> createChallenge({List<int>? serverPrivateKeyBytes}) async {
    serverPrivateKeyBytes ??= generateRandomBytes(32);
    serverPrivateKey = serverPrivateKeyBytes.toBigInt();
    // k = H(N,g)
    final multiplierParameter = (await _hashRfc5054(
        [safePrime.toByteList(), generator.toByteList()]
    )).toBigInt();
    // B = kv + g^b
    serverPublicKey = multiplierParameter * verifierKey + generator.modPow(serverPrivateKey!, safePrime);
    return Challenge(
      ephemeralServerPublicKey: serverPublicKey!.toByteList(),
      salt: salt,
    );
  }

  Future<List<int>> _hashRfc5054(List<List<int>> byteLists) async {
    //OPTIMIZE: Make this a class field.
    final safePrimeBytes = safePrime.toByteList();
    return hashRfc5054(
      byteLists: byteLists,
      safePrime: safePrimeBytes,
      hashAlgorithm: hashAlgorithm
    );
  }
}
